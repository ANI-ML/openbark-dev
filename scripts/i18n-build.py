"""Build apps/desktop/src/i18n/messages.ts from translation files.

Usage: python scripts/i18n-build.py packages/i18n/i18n-*.json
Each file maps English interface strings (from scripts/i18n-keys.py) to one
language; the language code is taken from the file name (i18n-<code>.json).
Refuses a file whose placeholders don't match the English, and reports
strings that have no translation (they show in English).
"""
import io
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "apps", "desktop", "src", "i18n", "messages.ts")
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def keys() -> list[str]:
    out = subprocess.run([sys.executable, os.path.join(HERE, "i18n-keys.py")], capture_output=True, text=True,
                         encoding="utf-8", check=True).stdout
    return json.loads(out)


def main(paths: list[str]) -> int:
    wanted = keys()
    catalogs: dict[str, dict[str, str]] = {}
    problems = 0
    for path in paths:
        code = re.search(r"i18n-(\w+)\.json$", path).group(1)
        with io.open(path, encoding="utf-8") as f:
            data: dict[str, str] = json.load(f)
        catalog = {}
        for key in wanted:
            value = data.get(key)
            if not value:
                print(f"{code}: no translation for {key!r} (shown in English)")
                continue
            if sorted(PLACEHOLDER.findall(key)) != sorted(PLACEHOLDER.findall(value)):
                print(f"{code}: placeholders differ for {key!r}: {value!r}")
                problems += 1
                continue
            catalog[key] = value
        extra = set(data) - set(wanted)
        if extra:
            print(f"{code}: {len(extra)} strings no longer in the app (dropped)")
        catalogs[code] = catalog
        print(f"{code}: {len(catalog)}/{len(wanted)} strings")
    if problems:
        print(f"{problems} problem(s); messages.ts not written")
        return 1
    lines = [
        "// Interface translations, keyed by the English text (src/i18n.ts).",
        "// Generated by scripts/i18n-build.py from packages/i18n/i18n-<code>.json; edit",
        "// those files and re-run the script (docs/languages.md).",
        "export const MESSAGES: Record<string, Record<string, string>> = {",
    ]
    for code in sorted(catalogs):
        lines.append(f"  {code}: {{")
        for key, value in catalogs[code].items():
            lines.append(f"    {json.dumps(key, ensure_ascii=False)}: {json.dumps(value, ensure_ascii=False)},")
        lines.append("  },")
    lines.append("};")
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.normpath(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
